// Builds the 1-bit dot pictures the 5100 can show, from their source images.
//   node tools/pictures.mjs <folder with the source images> [preview folder]
// Writes public/images/<name>.png and src/terminal/pictures.gen.ts.
// Sources are not in the repo: the lab photo is the Steins;Gate 100%
// achievement art, the rest are John Titor's 2000-2001 forum attachments.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const [srcDir, previewDir] = process.argv.slice(2);
if (!srcDir) {
  console.error("usage: node tools/pictures.mjs <source folder> [preview folder]");
  process.exit(1);
}

/** Dot rows per text row. Same for every picture so the dots all match. */
const DOTS_PER_ROW = 13.5;

const PICTURES = {
  labphoto: { src: "412830_3.jpg", rows: 12, aspect: 16 / 9, contrast: [1.35, -75], sharpen: 1.2 },
  // the red beam is the point of this one, so redness is added to brightness
  laser: { src: "fetch.jpg", rows: 13, crop: { left: 0, top: 3, width: 252, height: 203 }, contrast: [1.3, -15], sharpen: 1, red: 2.2 },
  unit: { src: "fetch3.jpg", rows: 13, crop: { left: 24, top: 24, width: 238, height: 170 }, contrast: [1.15, 30], sharpen: 1 },
  remote: { src: "fetch4.jpg", rows: 13, crop: { left: 24, top: 24, width: 238, height: 170 }, contrast: [1.15, 35], sharpen: 1 },
  blueprint: { src: "fetch6.jpg", rows: 13, crop: { left: 20, top: 40, width: 570, height: 400 }, invert: true, contrast: [1.6, -60], sharpen: 0.6 },
  diagram: { src: "fetch5.jpg", rows: 8, crop: { left: 30, top: 70, width: 400, height: 290 }, invert: true, contrast: [1.6, -60], sharpen: 0.6 },
};

const gen = [];
for (const [name, p] of Object.entries(PICTURES)) {
  let img = sharp(join(srcDir, p.src));
  if (p.crop) img = img.extract(p.crop);
  const meta = p.crop ?? (await sharp(join(srcDir, p.src)).metadata());
  const aspect = p.aspect ?? meta.width / meta.height;
  const h = Math.round(p.rows * DOTS_PER_ROW);
  const w = Math.round(h * aspect);
  img = img.resize(w, h, { fit: "cover", kernel: "lanczos3" });
  if (p.red) {
    // luma plus how much redder than green/blue a pixel is
    const k = p.red;
    img = sharp(await img.recomb([[0.3 + k, 0.59 - k / 2, 0.11 - k / 2], [0.3, 0.59, 0.11], [0.3, 0.59, 0.11]]).png().toBuffer());
  }
  img = img.grayscale();
  if (p.invert) img = img.negate({ alpha: false });
  const { data } = await img
    .normalise({ lower: 2, upper: 98 })
    .sharpen({ sigma: p.sharpen, m1: 1.5, m2: 3 })
    .linear(...p.contrast)
    .raw()
    .toBuffer({ resolveWithObject: true });

  // Floyd-Steinberg keeps faces and fine lines readable at this size.
  const px = Float32Array.from(data);
  const out = Buffer.alloc(w * h);
  for (let y = 0; y < h; y++)
    for (let x = 0; x < w; x++) {
      const i = y * w + x;
      const v = px[i] < 128 ? 0 : 255;
      out[i] = v;
      const err = px[i] - v;
      if (x + 1 < w) px[i + 1] += (err * 7) / 16;
      if (y + 1 < h) {
        if (x > 0) px[i + w - 1] += (err * 3) / 16;
        px[i + w] += (err * 5) / 16;
        if (x + 1 < w) px[i + w + 1] += err / 16;
      }
    }
  await sharp(out, { raw: { width: w, height: h, channels: 1 } })
    .png({ palette: true, colours: 2, compressionLevel: 9 })
    .toFile(`public/images/${name}.png`);
  gen.push(`  ${name}: { w: ${w}, h: ${h}, rows: ${p.rows} },`);
  console.log(`${name}: ${w}x${h} dots, ${p.rows} rows`);

  if (previewDir) {
    const S = 4;
    const buf = Buffer.alloc(w * S * h * S * 3);
    for (let y = 0; y < h * S; y++)
      for (let x = 0; x < w * S; x++) {
        const on = out[Math.floor(y / S) * w + Math.floor(x / S)] && x % S < S - 1 && y % S < S - 1;
        const o = (y * w * S + x) * 3;
        buf.set(on ? [0xdc, 0xf3, 0xd2] : [6, 9, 8], o);
      }
    await sharp(buf, { raw: { width: w * S, height: h * S, channels: 3 } }).png().toFile(join(previewDir, `${name}.png`));
  }
}

writeFileSync(
  "src/terminal/pictures.gen.ts",
  `// Generated by tools/pictures.mjs. Dot sizes of public/images/<name>.png.\n` +
    `export const PICTURES = {\n${gen.join("\n")}\n} as const;\n\nexport type PictureName = keyof typeof PICTURES;\n`,
);
